#!/usr/bin/env python3
"""Generate test-only Monkey C constants from the shared v1 fixture."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'watch/source/tests/Vectors.mc'

def generate():
    data = json.loads((ROOT / 'test-vectors/v1.json').read_text())
    lines = ['// Generated by watch/tools/generate_vectors.py; do not edit.',
             '(:test)', 'module Vectors {']
    for group in ('approval', 'pairing', 'framing'):
        for key, value in data[group].items():
            name = f'{group}_{key}'.upper()
            if isinstance(value, list):
                for i, item in enumerate(value):
                    lines.append(f'    const {name}_{i} = {json.dumps(item, ensure_ascii=False)};')
                lines.append(f'    const {name}_COUNT = {len(value)};')
            else:
                literal = json.dumps(value, ensure_ascii=False)
                lines.append(f'    const {name} = {literal};')
    # AuthHello and Error aren't in the JSON; construct their literal wire
    # representation using the fixture nonce and protocol's fixed error code.
    lines.append(f'    const AUTH_MESSAGE = "0101{data["pairing"]["watch_nonce"]}";')
    lines.append('    const ERROR_MESSAGE = "01ff02";')
    lines.append('}')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != result:
            raise SystemExit('Vectors.mc is stale; run watch/tools/generate_vectors.py')
        print('Vectors.mc matches test-vectors/v1.json')
    else:
        OUT.write_text(result)
        print(f'Generated {OUT.relative_to(ROOT)}')
